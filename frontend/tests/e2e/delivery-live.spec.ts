import { test, expect } from '@playwright/test'
import { readFileSync } from 'node:fs'

test('同源真实后台：合成流程、原件、草稿确认、待审反馈及刷新恢复；新生成拒绝', async ({page}, info) => {
  const config = JSON.parse(readFileSync(process.env.M7_BROWSER_CONFIG!, 'utf8'))
  expect(config.synthetic).toBe(true)
  const errors:string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/login')
  await page.getByLabel('用户名', {exact:true}).fill(config.username)
  await page.getByLabel('密码', {exact:true}).fill(config.password)
  await page.getByRole('button', {name:'登录', exact:true}).click()
  await expect(page.getByRole('button', {name:'新建会话',exact:true})).toBeVisible()
  await expect(page.getByRole('note').filter({hasText:'内部预览'})).toBeVisible()
  await page.goto('/documents')
  await expect(page.getByRole('heading', {name:'资料管理',exact:true})).toBeVisible()
  await expect(page.getByText('知衡自制预览资料.md', {exact:true})).toBeVisible()
  await page.screenshot({path:info.outputPath('documents.png'),fullPage:true})
  // HTTP路径经同源网关，未替换API；fixture标识始终保留。
  const citation = await page.request.get(`/api/v1/runs/${config.run_id}/citations/engineering-source`)
  expect(citation.status()).toBe(200)
  const original = (await citation.json()).original
  const pdf = await page.request.get(original.url, {headers:{Range:'bytes=0-4'}})
  expect(pdf.status()).toBe(206)
  expect((await pdf.body()).toString()).toBe('%PDF-')
  await page.goto(`/chat/${config.conversation_id}`)
  await expect(page.getByText('工程合成fixture，非模型回答。', {exact:false})).toBeVisible()
  await page.reload()
  await expect(page.getByText('工程合成fixture，非模型回答。', {exact:false})).toBeVisible()
  await page.getByLabel('问题', {exact:true}).fill('未授权的新生成不得执行')
  const refused = page.waitForResponse(r => r.url().endsWith('/runs') && r.request().method()==='POST')
  await page.getByRole('button', {name:'发送',exact:true}).click()
  expect((await refused).status()).toBe(503)
  await page.goto(`/cases?conversation=${config.conversation_id}&run=${config.run_id}`)
  await page.getByLabel('设备型号', {exact:true}).fill('工程合成设备 ZH-DEMO-1')
  await page.getByLabel('实际现象', {exact:true}).fill('工程协议演示，无新模型答案')
  await page.getByRole('button', {name:'保存确认信息与纠正',exact:true}).click()
  await page.getByRole('button', {name:'生成转交草稿',exact:true}).click()
  await page.getByLabel('处理摘要', {exact:true}).fill('工程合成草稿，用户确认演练；不能作为产品质量证明。')
  await page.getByRole('button', {name:'保存用户编辑',exact:true}).click()
  await page.getByRole('button', {name:'确认保存当前服务端草稿',exact:true}).click()
  await expect(page.getByRole('button', {name:'导出已确认 Markdown',exact:true})).toBeVisible()
  await page.getByLabel('反馈类别', {exact:true}).selectOption('evidence')
  await page.getByLabel('反馈内容', {exact:true}).fill('仅工程演练待审反馈，不是有效真实反馈proof。')
  const feedback = page.waitForResponse(r => r.url().endsWith('/feedback') && r.request().method()==='POST')
  await page.getByRole('button', {name:'提交待审反馈',exact:true}).click()
  const saved = await feedback
  expect(saved.status()).toBe(201)
  expect((await saved.json()).state).toBe('pending_review')
  await page.screenshot({path:info.outputPath('confirmed-feedback.png'),fullPage:true})
  expect(errors).toEqual([])
})
